"""水位继承戳 —— 全局唯一设计取舍：**继承戳锁模式**。

【题述取舍（全局只贯彻这一种）】
  甲·继承戳锁模式：戳写重置则从锚点事件时起算，戳写延续则保持切前水位；
    只改会话字段不得暗改已戳模式。
  乙·切流世代换票：若要改继承模式必须新开切流世代并重写戳，旧世代抬升入口整票拒绝。
本模块选定 **甲·继承戳锁模式**，换票只是锁模式的必然推论而非第二套口径：
  - 继承模式由「当前切流世代的戳」锁定；直播间.开播事件时等会话字段只是戳的投影，
    任何绕开切流事务的会话字段修改都与戳冲突，抬升写闸发现即整票拒绝；
  - 要改继承模式，唯一合法路径是重新开播/闭播（新开切流世代、同票重写戳），
    旧世代戳随之失效——不存在第二条改模通道。

【同票写戳】
开播/闭播事务提交前必须同票写入继承戳（房间、切流世代、切前水位、锚点事件时、
继承模式、戳号）；戳写失败或收尾核证不过 → 整票回滚，禁止切流成功继承戳空。

【硬约束】
  1. 禁止切流成功继承戳空（每条切流审计必须有同世代戳）；
  2. 禁止戳声明重置却水位仍高于锚点事件时（切流落票时水位须恰为锚点）；
  3. 禁止戳声明延续却被静默改小（落票水位须恰为切前水位，抬升不得跌破）。

【三闸协同】
  切流写闸：切流事务收尾 切流核证——断言水位行符合已戳模式，违例整票回滚；
  入流拒写闸：闸口关闭/跨代迟到由 切流.入流闸口校验 先行拒收（不触抬升）；
  抬升写闸：入流抬升前 抬升核证——戳缺失/会话字段暗改/水位跌破已戳地板，
    整票拒绝（批次回滚），开播后第一条抬升必须吃戳。
核证只读接口 查继承戳 汇总戳链与上述不变量，供切流台/热度窗页/贯验协同核对。
"""

from app.services import 时间

状态 = "已实现-继承戳锁模式"

# 继承模式词汇表：重置/延续为题述两口径；封存=闭播落票（水位不动）；创世=直建初代（非切流）
重置 = "重置"
延续 = "延续"
封存 = "封存"
创世 = "创世"
模式集 = (重置, 延续, 封存, 创世)


class 继承戳错误(Exception):
    """水位继承戳域错误基类：切流/抬升写闸失败闭，一律整票回滚。"""


class 戳缺失(继承戳错误):
    """切流成功继承戳空 / 当前世代无戳可吃。"""


class 戳会话不符(继承戳错误):
    """只改会话字段不换世代：会话字段与已戳锚点冲突。"""


class 戳水位违例(继承戳错误):
    """水位行违反已戳模式（重置未落锚点 / 延续被改小 / 封存被动）。"""


class 戳字段非法(继承戳错误):
    """戳字段缺失或未知模式——禁止半截戳。"""


def 写戳(conn, *, 房间键: str, 切流世代: int, 切前水位: str, 锚点事件时: str,
         继承模式: str, 处理时: str) -> dict:
    """同票写继承戳。字段任一缺失即拒绝——戳必须完整，禁止半截戳、禁止空锚点。

    戳号确定性生成（房+世代唯一），表上 (房间键,切流世代) 唯一索引兜底，
    同世代重复写直接撞约束失败闭，杜绝一脉双戳。
    """
    切流世代 = int(切流世代)
    if not 房间键:
        raise 戳字段非法("继承戳缺房间键，拒绝写戳")
    if 切流世代 <= 0:
        raise 戳字段非法(f"继承戳切流世代非法:{切流世代}，拒绝写戳")
    if not 切前水位:
        raise 戳字段非法("继承戳缺切前水位，拒绝写戳")
    if not 锚点事件时:
        raise 戳字段非法("继承戳缺锚点事件时，拒绝写戳")
    if 继承模式 not in 模式集:
        raise 戳字段非法(f"未知继承模式:{继承模式}，拒绝写戳")
    if not 处理时:
        raise 戳字段非法("继承戳缺时刻，拒绝写戳")
    戳号 = f"戳-{房间键}-e{切流世代}"
    conn.execute(
        """INSERT INTO 水位继承戳(房间键,切流世代,切前水位,锚点事件时,继承模式,戳号,时刻)
           VALUES (?,?,?,?,?,?,?)""",
        (房间键, 切流世代, 切前水位, 锚点事件时, 继承模式, 戳号, 处理时),
    )
    return {
        "房间键": 房间键, "切流世代": 切流世代, "切前水位": 切前水位,
        "锚点事件时": 锚点事件时, "继承模式": 继承模式, "戳号": 戳号, "时刻": 处理时,
    }


def 取戳(conn, 房间键: str, 切流世代: int):
    """按（房间,世代）取戳——抬升写闸与切流写闸的口粮。"""
    return conn.execute(
        "SELECT * FROM 水位继承戳 WHERE 房间键=? AND 切流世代=?",
        (房间键, int(切流世代)),
    ).fetchone()


def 当前戳(conn, 房间键: str):
    """房间最新一代戳（只读接口用）。"""
    return conn.execute(
        "SELECT * FROM 水位继承戳 WHERE 房间键=? ORDER BY 切流世代 DESC, 编号 DESC LIMIT 1",
        (房间键,),
    ).fetchone()


def 戳地板(戳) -> str:
    """已戳模式锁定的水位地板：重置/创世→锚点事件时；延续/封存→切前水位。"""
    if 戳["继承模式"] in (重置, 创世):
        return 戳["锚点事件时"]
    return 戳["切前水位"]


def 切流核证(conn, 房间键: str, 切流世代: int) -> None:
    """切流写闸：切流事务收尾（提交前）断言本票自洽，违例即抛 → 整票回滚。

    - 禁止切流成功继承戳空：本世代戳必须已同票写入；
    - 戳写重置 → 水位行须恰为锚点事件时（禁止仍高于锚点，也禁止低于）；
    - 戳写延续/封存 → 水位行须恰为切前水位（禁止静默改小，也禁止暗抬）。
    """
    戳 = 取戳(conn, 房间键, 切流世代)
    if 戳 is None:
        raise 戳缺失(f"切流成功继承戳空：{房间键} e{切流世代} 无同票继承戳，整票回滚")
    行 = conn.execute(
        "SELECT 事件时水位 FROM 水位线 WHERE 房间键=?", (房间键,)
    ).fetchone()
    水位 = 行["事件时水位"] if 行 else None
    模式 = 戳["继承模式"]
    if 模式 == 重置:
        if 水位 is None or 时间.解析(水位) != 时间.解析(戳["锚点事件时"]):
            方向 = "仍高于" if (水位 and 时间.解析(水位) > 时间.解析(戳["锚点事件时"])) else "未落到"
            raise 戳水位违例(
                f"戳声明重置却水位{方向}锚点事件时：水位{水位} 锚点{戳['锚点事件时']}，整票回滚"
            )
    elif 模式 in (延续, 封存):
        if 水位 is None or 时间.解析(水位) != 时间.解析(戳["切前水位"]):
            方向 = "被静默改小" if (水位 and 时间.解析(水位) < 时间.解析(戳["切前水位"])) else "被暗改"
            raise 戳水位违例(
                f"戳声明{模式}却水位{方向}：水位{水位} 切前水位{戳['切前水位']}，整票回滚"
            )


def 抬升核证(conn, 房间键: str, 切流世代: int):
    """抬升写闸：开播后每次抬升前必须吃本世代戳。违例即抛 → 批次整票回滚。

    - 戳缺失 → 切流成功继承戳空，抬升整票拒绝；
    - 会话字段（直播间.开播事件时）≠ 戳锚点 → 只改会话字段不换世代，整票拒绝；
    - 水位跌破已戳地板（重置→锚点；延续→切前水位）→ 被静默改小，整票拒绝。
    通过则返回戳行，抬升按戳锁定的地板向上推进。
    """
    戳 = 取戳(conn, 房间键, 切流世代)
    if 戳 is None:
        raise 戳缺失(
            f"房间{房间键}切流世代e{切流世代}无继承戳：切流成功继承戳空，抬升整票拒绝"
        )
    房 = conn.execute(
        "SELECT 状态,开播事件时 FROM 直播间 WHERE 房间键=?", (房间键,)
    ).fetchone()
    if 房 and 时间.解析(房["开播事件时"]) != 时间.解析(戳["锚点事件时"]):
        raise 戳会话不符(
            f"房间{房间键}只改会话字段不换世代：开播事件时{房['开播事件时']}≠继承戳锚点"
            f"{戳['锚点事件时']}（e{切流世代}·{戳['继承模式']}），继承模式已被戳锁定，"
            f"抬升整票拒绝；欲改模式须新开切流世代重写戳"
        )
    行 = conn.execute(
        "SELECT 事件时水位 FROM 水位线 WHERE 房间键=?", (房间键,)
    ).fetchone()
    if 行:
        地板 = 戳地板(戳)
        if 时间.解析(行["事件时水位"]) < 时间.解析(地板):
            raise 戳水位违例(
                f"房间{房间键}水位{行['事件时水位']}低于已戳{戳['继承模式']}地板{地板}："
                f"疑似被静默改小，抬升整票拒绝"
            )
    return 戳


def 查继承戳(conn, 房间键: str | None = None) -> dict:
    """水位继承核证只读接口：戳链 + 三硬约束核证 + 四闸协同快照。

    与切流写闸（同票戳、落票自洽）、抬升写闸（当前世代戳可吃）、
    入流拒写闸（闸口/拒收数）、热度窗页（开启窗须落在当前戳世代）协同。
    """
    if 房间键:
        房键列 = [房间键]
    else:
        房键列 = [
            r["房间键"] for r in conn.execute("SELECT 房间键 FROM 直播间 ORDER BY 房间键")
        ]
    问题 = []
    房快照 = []
    全部戳 = []
    for 键 in 房键列:
        房 = conn.execute("SELECT * FROM 直播间 WHERE 房间键=?", (键,)).fetchone()
        if not 房:
            问题.append(f"未知直播间:{键}")
            continue
        闸 = conn.execute("SELECT * FROM 入流闸 WHERE 房间键=?", (键,)).fetchone()
        水位行 = conn.execute("SELECT * FROM 水位线 WHERE 房间键=?", (键,)).fetchone()
        戳列 = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 水位继承戳 WHERE 房间键=? ORDER BY 切流世代,编号", (键,)
            )
        ]
        审计列 = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 切流审计 WHERE 房间键=? ORDER BY 切流代次,编号", (键,)
            )
        ]
        全部戳.extend(戳列)
        戳按代 = {int(s["切流世代"]): s for s in 戳列}
        审计按代 = {int(a["切流代次"]): a for a in 审计列}

        # 硬约束一：禁止切流成功继承戳空（每条切流审计须有同世代戳）
        for a in 审计列:
            if int(a["切流代次"]) not in 戳按代:
                问题.append(
                    f"{键}:切流e{a['切流代次']}({a['切流态']})成功却无同票继承戳——切流成功继承戳空"
                )
        # 反向：非创世戳必须能回溯到切流审计（戳不凭空）
        for s in 戳列:
            if s["继承模式"] != 创世 and int(s["切流世代"]) not in 审计按代:
                问题.append(f"{键}:继承戳{s['戳号']}无对应切流审计——戳链不可信")

        # 硬约束二/三：戳声明模式 vs 切流落票水位（以切流审计为证）
        for s in 戳列:
            a = 审计按代.get(int(s["切流世代"]))
            if not a:
                continue
            if a["切流态"] == "直播中" and s["继承模式"] == 重置:
                if 时间.解析(a["切流后水位"]) != 时间.解析(s["锚点事件时"]):
                    方向 = (
                        "仍高于"
                        if 时间.解析(a["切流后水位"]) > 时间.解析(s["锚点事件时"])
                        else "低于"
                    )
                    问题.append(
                        f"{键}:e{s['切流世代']}戳声明重置却切流后水位{方向}锚点事件时："
                        f"{a['切流后水位']} vs {s['锚点事件时']}"
                    )
            if a["切流态"] == "直播中" and s["继承模式"] == 延续:
                if 时间.解析(a["切流后水位"]) < 时间.解析(s["切前水位"]):
                    问题.append(
                        f"{键}:e{s['切流世代']}戳声明延续却被静默改小："
                        f"{a['切流后水位']}<{s['切前水位']}"
                    )
            if s["继承模式"] == 封存:
                if 时间.解析(a["切流后水位"]) != 时间.解析(s["切前水位"]):
                    问题.append(
                        f"{键}:e{s['切流世代']}闭播封存水位被动过："
                        f"{a['切流后水位']}≠{s['切前水位']}"
                    )

        # 抬升写闸口粮：当前世代戳必须在
        当代 = int(闸["切流代次"]) if 闸 else None
        当前 = 戳按代.get(当代) if 当代 is not None else None
        if 闸 and 当前 is None:
            问题.append(f"{键}:当前切流世代e{当代}无继承戳，抬升写闸将整票拒绝")

        # 锁模式：只改会话字段不得暗改已戳模式（直播中房的会话投影须与戳一致）
        if 房["状态"] == "直播中" and 当前:
            if 时间.解析(房["开播事件时"]) != 时间.解析(当前["锚点事件时"]):
                问题.append(
                    f"{键}:只改会话字段不换世代——开播事件时{房['开播事件时']}≠"
                    f"戳锚点{当前['锚点事件时']}（e{当代}·{当前['继承模式']}）"
                )
        # 水位不得跌破已戳地板（直播中房）
        if 房["状态"] == "直播中" and 当前 and 水位行:
            地板 = 戳地板(当前)
            if 时间.解析(水位行["事件时水位"]) < 时间.解析(地板):
                问题.append(
                    f"{键}:水位{水位行['事件时水位']}低于已戳{当前['继承模式']}地板{地板}"
                )

        # 双水位并存结构断言：水位行每房恰一行
        n水 = conn.execute(
            "SELECT COUNT(*) AS c FROM 水位线 WHERE 房间键=?", (键,)
        ).fetchone()["c"]
        if n水 != 1:
            问题.append(f"{键}:水位行数={n水}，须恰为1（禁止双水位并存/水位缺失）")

        # 热度窗页协同：开启窗须落在当前戳世代
        开启窗数 = conn.execute(
            "SELECT COUNT(*) AS c FROM 热度窗 WHERE 房间键=? AND 状态='开启'", (键,)
        ).fetchone()["c"]
        if 闸:
            串 = conn.execute(
                "SELECT COUNT(*) AS c FROM 热度窗 WHERE 房间键=? AND 状态='开启' AND 切流代次<>?",
                (键, 当代),
            ).fetchone()["c"]
            if 串:
                问题.append(f"{键}:{串}个开启窗落在旧世代，与当前戳世代e{当代}不符")

        # 入流拒写闸协同快照
        拒收数 = conn.execute(
            "SELECT COUNT(*) AS c FROM 互动事件 WHERE 房间键=? AND 命运='切流拒收'", (键,)
        ).fetchone()["c"]
        房快照.append(
            {
                "房间键": 键,
                "切流态": 房["状态"],
                "入流闸开放": bool(闸 and 闸["开放"]),
                "当前世代": 当代,
                "当前水位": 水位行["事件时水位"] if 水位行 else None,
                "当前戳": 当前,
                "戳数": len(戳列),
                "开启窗数": 开启窗数,
                "切流拒收数": 拒收数,
            }
        )
    return {
        "继承戳": 全部戳,
        "锁模式": True,
        "采信会话态": False,
        "口径": "继承戳锁模式：戳写重置则从锚点事件时起算，戳写延续则保持切前水位；"
              "只改会话字段不得暗改已戳模式，改模式须新开切流世代重写戳",
        "核证": {"valid": not 问题, "问题": 问题},
        "房间": 房快照,
    }
