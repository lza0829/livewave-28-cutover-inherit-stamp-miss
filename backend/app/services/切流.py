"""开播闭播切流 —— 兼容性状态机（全局唯一口径：重置水位 RESET）。

【架构取舍（全局只贯彻这一种）】
本可以有两种口径：
  甲·重置水位：开播事务把水位重置为开播事件时；开播后第一条事件，事件时 ≥
    开播事件时则从重置水位推进；闭播后拒绝一切正式入窗。
  乙·延续水位：开播不改水位数值，继续在原水位之上推进。
本模块选定 **甲·重置水位**。两口径在「历史水位已很高时执行开播，随后读水位」
上的正确性结论必须可区分——甲：水位降到开播事件时；乙：水位保持高值。
测试 `backend/tests/test_切流.py` 把该判别钉死。

【继承戳锁模式（与 modules/水位继承戳 同一把锁）】
每次切流（开播/闭播）必须同票写继承戳：房间、切流世代、切前水位、锚点事件时、
继承模式、戳号；戳写失败或收尾核证不过 → 整票回滚，禁止切流成功继承戳空。
开播后抬升必须吃本世代戳（抬升写闸，见 services/装载.py）：
只改会话字段不换世代 → 抬升整票拒绝；欲改继承模式须新开切流世代重写戳。

【防重开历史窗】
切流代次（epoch）随每次开播/闭播 +1，并写入热度窗窗键
（``房|代次|窗起``）。重置水位后，新代次的窗键与历史窗永不撞键，
已关闭的历史窗在结构上不可能被重开扫描；旧代次窗在闭播时全部关尽。

【失败闭并发】
开播/闭播/入流都在 ``db.写事务`` 的 BEGIN IMMEDIATE 临界区内执行，
同库同时刻只允许一个写事务；抢锁失败抛错由路由转 409。
临界区内重读闸口/状态再判定，禁止切流半截、禁止双水位并存。

【闭播后入流】
闸口关闭后，正式入窗一律拒收：互动事件落命运「切流拒收」，
同时进旁路匣（原因「切流拒收-…」）并可在切流审计时间线查询。
"""

from app.db import 连接, 写事务
from app.modules import 水位继承戳
from app.seed import 此刻
from app.services import 时间, 热度窗

直播中 = "直播中"
已闭播 = "已闭播"
口径 = "重置水位"


class 切流错误(Exception):
    """切流域错误基类。"""


class 状态冲突(切流错误):
    """非法状态跃迁（如直播中再开播、已闭播再闭播）。"""


class 闸口关闭(切流错误):
    """闭播后仍有正式入流——失败闭拒收。"""


class 跨代迟到(切流错误):
    """重开后收到事件时早于新开播事件时的旧代次事件。"""


def 取房(conn, 房间键: str):
    房 = conn.execute("SELECT * FROM 直播间 WHERE 房间键=?", (房间键,)).fetchone()
    if not 房:
        raise 切流错误(f"未知直播间:{房间键}")
    return 房


def 取闸(conn, 房间键: str):
    return conn.execute("SELECT * FROM 入流闸 WHERE 房间键=?", (房间键,)).fetchone()


def 取水位(conn, 房间键: str):
    return conn.execute("SELECT * FROM 水位线 WHERE 房间键=?", (房间键,)).fetchone()


def _记审计(conn, 房间键, 切流态, 代次, 开播事件时, 前水位, 后水位, 处理时, 结果="已执行", 说明=""):
    conn.execute(
        """INSERT INTO 切流审计(房间键,切流态,切流代次,开播事件时,切流前水位,切流后水位,处理时,结果,说明)
           VALUES (?,?,?,?,?,?,?,?,?)""",
        (房间键, 切流态, 代次, 开播事件时, 前水位, 后水位, 处理时, 结果, 说明),
    )


def _关尽开启窗(conn, 房间键: str, 处理时: str) -> int:
    """闭播/开播代次切换前，把该房所有开启窗关尽，禁止旧代次窗悬挂。"""
    n = 0
    for 窗 in conn.execute(
        "SELECT * FROM 热度窗 WHERE 房间键=? AND 状态='开启'", (房间键,)
    ).fetchall():
        conn.execute(
            "UPDATE 热度窗 SET 状态='已关闭', 关闭处理时=?, 版本=CASE WHEN 版本=0 THEN 1 ELSE 版本 END WHERE 窗键=?",
            (处理时, 窗["窗键"]),
        )
        n += 1
    return n


def 开播(房间键: str, 开播事件时: str | None = None, 处理时: str | None = None) -> dict:
    """重开直播（仅可由已闭播跃迁）。

    reset 口径事务内一步完成：状态→直播中；闸口开放、代次+1；
    水位**重置**为开播事件时；旧代次开启窗关尽；**同票写继承戳（锁模式·重置）**；
    写切流审计（含前后水位）；收尾切流核证——任一步失败整票回滚，
    禁止切流成功继承戳空、禁止戳声明重置却水位仍高于锚点事件时。
    """
    处理时 = 处理时 or 此刻()
    with 写事务() as conn:
        房 = 取房(conn, 房间键)
        if 房["状态"] != 已闭播:
            raise 状态冲突(f"房间{房间键}当前为「{房['状态']}」，不可开播；仅已闭播房可重开")
        闸 = 取闸(conn, 房间键)
        if 闸 is None:
            raise 切流错误(f"房间{房间键}入流闸缺失，失败闭拒绝开播")
        新代次 = int(闸["切流代次"]) + 1
        新开播时 = 开播事件时 or 处理时
        旧水位行 = 取水位(conn, 房间键)
        前水位 = 旧水位行["事件时水位"] if 旧水位行 else 房["开播事件时"]

        关窗数 = _关尽开启窗(conn, 房间键, 处理时)
        conn.execute(
            "UPDATE 直播间 SET 状态=?, 开播事件时=? WHERE 房间键=?",
            (直播中, 新开播时, 房间键),
        )
        conn.execute(
            """INSERT INTO 水位线(房间键,事件时水位,允许迟到秒,更新处理时)
               VALUES (?,?,?,?)
               ON CONFLICT(房间键) DO UPDATE SET 事件时水位=excluded.事件时水位, 更新处理时=excluded.更新处理时""",
            (房间键, 新开播时, int(旧水位行["允许迟到秒"]) if 旧水位行 else 30, 处理时),
        )
        conn.execute(
            "UPDATE 入流闸 SET 开放=1, 切流代次=?, 更新处理时=? WHERE 房间键=?",
            (新代次, 处理时, 房间键),
        )
        # 同票写继承戳（锁模式·重置）：戳与切流态同票生死，戳写失败 → 整票回滚
        戳 = 水位继承戳.写戳(
            conn, 房间键=房间键, 切流世代=新代次, 切前水位=前水位,
            锚点事件时=新开播时, 继承模式=水位继承戳.重置, 处理时=处理时,
        )
        _记审计(conn, 房间键, 直播中, 新代次, 新开播时, 前水位, 新开播时, 处理时,
                说明=f"重置水位：{前水位} → {新开播时}；旧代次关窗{关窗数}；继承戳{戳['戳号']}同票落票")
        # 切流写闸：提交前断言水位行符合已戳模式，违例整票回滚
        水位继承戳.切流核证(conn, 房间键, 新代次)
        return {
            "房间键": 房间键, "切流态": 直播中, "切流代次": 新代次,
            "切流前水位": 前水位, "切流后水位": 新开播时, "旧代次关窗": 关窗数,
            "继承戳": 戳["戳号"],
        }


def 闭播(房间键: str, 处理时: str | None = None) -> dict:
    """结束直播（仅可由直播中跃迁）：关尽开启窗、闸口关闭、代次+1、水位数值不动、
    同票写继承戳（封存）、写审计；收尾切流核证，任一步失败整票回滚。"""
    处理时 = 处理时 or 此刻()
    with 写事务() as conn:
        房 = 取房(conn, 房间键)
        if 房["状态"] != 直播中:
            raise 状态冲突(f"房间{房间键}当前为「{房['状态']}」，不可闭播；仅直播中房可闭播")
        闸 = 取闸(conn, 房间键)
        if 闸 is None:
            raise 切流错误(f"房间{房间键}入流闸缺失，失败闭拒绝闭播")
        新代次 = int(闸["切流代次"]) + 1
        水位行 = 取水位(conn, 房间键)
        现水位 = 水位行["事件时水位"] if 水位行 else 房["开播事件时"]

        关窗数 = _关尽开启窗(conn, 房间键, 处理时)
        conn.execute("UPDATE 直播间 SET 状态=? WHERE 房间键=?", (已闭播, 房间键))
        conn.execute(
            "UPDATE 入流闸 SET 开放=0, 切流代次=?, 更新处理时=? WHERE 房间键=?",
            (新代次, 处理时, 房间键),
        )

        conn.execute(
            "UPDATE 水位线 SET 更新处理时=? WHERE 房间键=?", (处理时, 房间键)
        )
        # 同票写继承戳（封存）：锚点沿用本场开播事件时，水位冻结于切前水位
        戳 = 水位继承戳.写戳(
            conn, 房间键=房间键, 切流世代=新代次, 切前水位=现水位,
            锚点事件时=房["开播事件时"], 继承模式=水位继承戳.封存, 处理时=处理时,
        )
        _记审计(conn, 房间键, 已闭播, 新代次, 房["开播事件时"], 现水位, 现水位, 处理时,
                说明=f"闭播关闸；关窗{关窗数}；水位保持{现水位}；继承戳{戳['戳号']}同票落票")
        # 切流写闸：提交前断言水位行符合已戳封存模式，违例整票回滚
        水位继承戳.切流核证(conn, 房间键, 新代次)
        return {
            "房间键": 房间键, "切流态": 已闭播, "切流代次": 新代次,
            "切流前水位": 现水位, "切流后水位": 现水位, "关窗": 关窗数,
            "继承戳": 戳["戳号"],
        }


def 入流闸口校验(conn, 房间键: str, 事件时: str):
    """入流临界区内调用：重读闸口与状态做失败闭判定。

    - 闸口缺失/关闭 → 闸口关闭（闭播后正式入窗拒收）
    - 直播中但事件时 < 开播事件时 → 跨代迟到（旧代次事件不得污染新场）
    返回闸口行（含切流代次，供窗键隔离使用）。
    """
    房 = 取房(conn, 房间键)
    闸 = 取闸(conn, 房间键)
    if 闸 is None or int(闸["开放"]) == 0 or 房["状态"] != 直播中:
        raise 闸口关闭(f"房间{房间键}已闭播/闸口关闭，正式入窗失败闭拒收")
    if 时间.解析(事件时) < 时间.解析(房["开播事件时"]):
        raise 跨代迟到(
            f"事件时{事件时}早于本代次开播事件时{房['开播事件时']}，属旧代次迟到，拒收"
        )
    return 闸


def 取切流态(房间键: str) -> dict:
    """切流只读接口：房间、切流态、开播前后水位、valid，及协同对象快照。"""
    conn = 连接()
    try:
        房 = conn.execute("SELECT * FROM 直播间 WHERE 房间键=?", (房间键,)).fetchone()
        if not 房:
            raise 切流错误(f"未知直播间:{房间键}")
        闸 = 取闸(conn, 房间键)
        水位 = 取水位(conn, 房间键)
        审计 = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 切流审计 WHERE 房间键=? ORDER BY 编号 DESC", (房间键,)
            ).fetchall()
        ]
        末次开播 = next((r for r in 审计 if r["切流态"] == 直播中), None)
        末次闭播 = next((r for r in 审计 if r["切流态"] == 已闭播), None)
        拒收数 = conn.execute(
            "SELECT COUNT(*) AS c FROM 互动事件 WHERE 房间键=? AND 命运='切流拒收'",
            (房间键,),
        ).fetchone()["c"]
        开启窗 = [
            dict(r)
            for r in conn.execute(
                "SELECT * FROM 热度窗 WHERE 房间键=? AND 状态='开启' ORDER BY 窗起事件时",
                (房间键,),
            ).fetchall()
        ]
        问题 = _一致性问题(conn, 房, 闸, 水位, 开启窗, 审计)
        当前戳 = (
            水位继承戳.取戳(conn, 房间键, int(闸["切流代次"])) if 闸 else None
        )
        return {
            "房间键": 房间键,
            "标题": 房["标题"],
            "切流态": 房["状态"],
            "直播间状态": 房["状态"],
            "开播事件时": 房["开播事件时"],
            "入流闸开放": bool(闸 and 闸["开放"]),
            "切流代次": int(闸["切流代次"]) if 闸 else None,
            "当前水位": 水位["事件时水位"] if 水位 else None,
            "允许迟到秒": int(水位["允许迟到秒"]) if 水位 else None,
            "继承戳": dict(当前戳) if 当前戳 else None,
            "末次开播": 末次开播,
            "末次闭播": 末次闭播,
            "开播前水位": 末次开播["切流前水位"] if 末次开播 else None,
            "开播后水位": 末次开播["切流后水位"] if 末次开播 else None,
            "拒收数": 拒收数,
            "开启窗": 开启窗,
            "审计": 审计,
            "valid": not 问题,
            "问题": 问题,
        }
    finally:
        conn.close()


def _一致性问题(conn, 房, 闸, 水位, 开启窗, 审计) -> list:
    问题 = []
    if 闸 is None:
        问题.append("入流闸缺失")
        return 问题
    
    if 房["状态"] == 直播中 and int(闸["开放"]) != 1:
        问题.append("直播中但入流闸未开放")
    if 房["状态"] == 已闭播 and int(闸["开放"]) != 0:
        问题.append("已闭播但入流闸仍开放")
    
    if 水位 and 房["状态"] == 直播中 and 时间.解析(水位["事件时水位"]) < 时间.解析(房["开播事件时"]):
        问题.append(
            f"水位{水位['事件时水位']}低于开播事件时{房['开播事件时']}，违反重置口径"
        )
    
    if 房["状态"] == 已闭播 and 开启窗:
        问题.append(f"已闭播仍有{len(开启窗)}个开启窗")
    
    for w in 开启窗:
        if int(w["切流代次"]) != int(闸["切流代次"]):
            问题.append(f"开启窗{w['窗键']}代次{w['切流代次']}≠闸代次{闸['切流代次']}")
    
    升序 = list(reversed(审计))
    for a, b in zip(升序, 升序[1:]):
        if int(b["切流代次"]) != int(a["切流代次"]) + 1:
            问题.append(f"切流代次链断裂：{a['切流代次']}→{b['切流代次']}")
    if 升序 and int(闸["切流代次"]) != int(升序[-1]["切流代次"]):
        问题.append("入流闸代次与末次切流审计不一致")
    末次开播 = next((r for r in 审计 if r["切流态"] == 直播中), None)
    末次闭播 = next((r for r in 审计 if r["切流态"] == 已闭播), None)
    
    if 末次闭播 and not (
        末次开播 and 时间.解析(末次开播["处理时"]) > 时间.解析(末次闭播["处理时"])
    ):
        脏 = conn.execute(
            "SELECT COUNT(*) AS c FROM 互动事件 WHERE 房间键=? AND 命运='已入窗' AND 处理时>?",
            (房["房间键"], 末次闭播["处理时"]),
        ).fetchone()["c"]
        if 脏:
            问题.append(f"闭播后仍有{脏}笔正式入窗事件，缺失败闭")
    
    if 末次开播 and 水位 and 房["状态"] == 直播中:
        if 时间.解析(水位["事件时水位"]) < 时间.解析(末次开播["切流后水位"]):
            问题.append("水位低于末次开播重置点，重置口径被破坏")

    # 继承戳锁模式协同：当前世代戳必须在、会话投影须与戳一致、水位须守住已戳地板
    当前戳 = 水位继承戳.取戳(conn, 房["房间键"], int(闸["切流代次"]))
    if 当前戳 is None:
        问题.append(f"当前切流世代e{闸['切流代次']}继承戳缺失——切流成功继承戳空")
    else:
        if 房["状态"] == 直播中 and 时间.解析(房["开播事件时"]) != 时间.解析(当前戳["锚点事件时"]):
            问题.append(
                f"只改会话字段不换世代：开播事件时{房['开播事件时']}≠"
                f"继承戳锚点{当前戳['锚点事件时']}（{当前戳['继承模式']}已锁定）"
            )
        if 房["状态"] == 直播中 and 水位:
            地板 = 水位继承戳.戳地板(当前戳)
            if 时间.解析(水位["事件时水位"]) < 时间.解析(地板):
                问题.append(
                    f"水位{水位['事件时水位']}低于继承戳{当前戳['继承模式']}地板{地板}，疑似被静默改小"
                )
    return 问题


def 列审计(房间键: str = "", 限: int = 100) -> list:
    """切流审计时间线：切流跃迁 + 入流拒收（取自旁路匣的切流拒收记录）。"""
    conn = 连接()
    try:
        if 房间键:
            行 = conn.execute(
                "SELECT * FROM 切流审计 WHERE 房间键=? ORDER BY 编号 DESC LIMIT ?",
                (房间键, 限),
            ).fetchall()
        else:
            行 = conn.execute(
                "SELECT * FROM 切流审计 ORDER BY 编号 DESC LIMIT ?", (限,)
            ).fetchall()
        return [dict(r) for r in 行]
    finally:
        conn.close()


def 是否锁冲突(exc: Exception) -> bool:
    msg = str(exc).lower()
    return "database is locked" in msg or "database table is locked" in msg
