def 断言(cond, 消息):
    global 通过
    if not cond:
        raise AssertionError(消息)
    通过 += 1
    print(f"  ✓ {消息}")


def 建房(键, 开播时, 状态=切流.直播中, 水位=None, 闸开=1, 代次=1):
    conn = 连接()
    conn.execute(
        "INSERT INTO 直播间(房间键,标题,主播,开播事件时,状态) VALUES (?,?,?,?,?)",
        (键, "测试房", "测", 开播时, 状态),
    )
    conn.execute(
        "INSERT INTO 水位线(房间键,事件时水位,允许迟到秒,更新处理时) VALUES (?,?,?,?)",
        (键, 水位 or 开播时, 30, "2026-11-22T00:00:00Z"),
    )
    conn.execute(
        "INSERT INTO 入流闸(房间键,开放,切流代次,更新处理时) VALUES (?,?,?,?)",
        (键, 闸开, 代次, "2026-11-22T00:00:00Z"),
    )
    conn.commit()
    conn.close()


def 事件(编号, 房, 时, 赞=1, 处理时=None):
    return {
        "事件编号": 编号, "房间键": 房, "事件类型": "点赞",
        "事件时": 时, "处理时": 处理时 or 时, "观众键": "观",
        "点赞增量": 赞, "送礼额": 0,
    }


def 读水位(房):
    conn = 连接()
    r = conn.execute("SELECT 事件时水位 FROM 水位线 WHERE 房间键=?", (房,)).fetchone()
    conn.close()
    return r["事件时水位"]



